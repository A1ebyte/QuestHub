    titulo TEXT,
    video TEXT,
    videojuego BIGINT,

    CONSTRAINT fk_movie_videojuego
        FOREIGN KEY (videojuego)
        REFERENCES public.videojuego(id_videojuego)
        ON DELETE CASCADE

);

CREATE TABLE IF NOT EXISTS bundle_productos_capturas (
    bundle_productos_steam_app_id bigint NOT NULL,
    imagen varchar(255),
    miniatura varchar(255),
    CONSTRAINT fk_bp_capturas
        FOREIGN KEY (bundle_productos_steam_app_id)

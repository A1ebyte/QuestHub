BEGIN;

-- TABLAS PRINCIPALES

CREATE TABLE IF NOT EXISTS bundle (
    id_bundle bigint PRIMARY KEY,
    imagen_url text,
    nombre varchar(255)
);


CREATE TABLE IF NOT EXISTS bundle_productos (
    steam_app_id bigint PRIMARY KEY,
    descripcion text,
    imagen_url text,
    nombre varchar(255),
    bundle bigint,
    CONSTRAINT fk_bundle_productos_bundle
        FOREIGN KEY (bundle)
        REFERENCES public.bundle(id_bundle)
        ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS tienda (
    id_tienda BIGINT PRIMARY KEY,
    banner TEXT,
    icon TEXT,
    logo TEXT,
    nombre VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS genero (
    id_genre BIGINT PRIMARY KEY,
    descripcion VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS usuario (
    id_usuario UUID PRIMARY KEY,
    email VARCHAR(255) UNIQUE,
    recibir_notificaciones BOOLEAN NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS videojuego (
    id_videojuego BIGINT PRIMARY KEY,
    acerca_de TEXT,
    desarolladores VARCHAR(255),
    descripcion TEXT,
    descripcion_corta TEXT,
    distribuidora VARCHAR(255),
    fecha_lanzamiento DATE,
    imagen_url TEXT,
    imagen_url_resolucion_baja TEXT,
    nombre VARCHAR(255),
    steam_rating_percent INTEGER,
    steam_rating_text VARCHAR(255)
);

-- TABLAS RELACIONALES


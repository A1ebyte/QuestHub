);

-- OFERTAS

CREATE TABLE IF NOT EXISTS oferta (
    id_oferta VARCHAR(255) PRIMARY KEY,

    ahorro DOUBLE PRECISION,
    cambiar_img BOOLEAN DEFAULT false,

    inicio_oferta TIMESTAMP,

    oferta_rating DOUBLE PRECISION,

    precio_oferta DOUBLE PRECISION NOT NULL,
    precio_original DOUBLE PRECISION NOT NULL,

    steam_appid BIGINT NOT NULL,

    steam_rating INTEGER,

    thumb TEXT,
    titulo VARCHAR(255),

    url_compra TEXT,

    tienda BIGINT,
    videojuego BIGINT,
    bundle BIGINT,

    url_imagen TEXT,

    CONSTRAINT fk_oferta_tienda
        FOREIGN KEY (tienda)
        REFERENCES public.tienda(id_tienda)
        ON DELETE SET NULL,

    CONSTRAINT fk_oferta_videojuego
        FOREIGN KEY (videojuego)
        REFERENCES public.videojuego(id_videojuego)
        ON DELETE CASCADE,

    CONSTRAINT fk_oferta_bundle
        FOREIGN KEY (bundle)
        REFERENCES public.bundle(id_bundle)
        ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS oferta_staging (
    id_oferta VARCHAR(255) PRIMARY KEY,

    ahorro DOUBLE PRECISION,
    cambiar_img BOOLEAN DEFAULT false,

    inicio_oferta TIMESTAMP,

    oferta_rating DOUBLE PRECISION,

    precio_oferta DOUBLE PRECISION NOT NULL,
    precio_original DOUBLE PRECISION NOT NULL,

    steam_appid BIGINT NOT NULL,

    steam_rating INTEGER,

    thumb TEXT,
    titulo VARCHAR(255),

    url_compra TEXT,

    tienda BIGINT,
    videojuego BIGINT,
    bundle BIGINT,

    CONSTRAINT fk_oferta_staging_tienda
        FOREIGN KEY (tienda)
        REFERENCES public.tienda(id_tienda)
        ON DELETE SET NULL,

    CONSTRAINT fk_oferta_staging_videojuego
        FOREIGN KEY (videojuego)
        REFERENCES public.videojuego(id_videojuego)
        ON DELETE CASCADE,

    CONSTRAINT fk_oferta_staging_bundle
        FOREIGN KEY (bundle)
        REFERENCES public.bundle(id_bundle)
        ON DELETE SET NULL
);

-- MATERIALIZED VIEW

CREATE MATERIALIZED VIEW IF NOT EXISTS mv_ofertas_unicas AS
WITH cheapest AS (
    SELECT DISTINCT ON (o.steam_appid)
        o.steam_appid,
        o.titulo,
        o.precio_oferta,
        o.ahorro,
        o.oferta_rating,
        o.inicio_oferta AS recent,
        o.steam_rating AS reviews,
        o.thumb AS imagen
    FROM public.oferta o
    ORDER BY
        o.steam_appid,
        o.precio_oferta ASC,
        o.oferta_rating DESC NULLS LAST
),

tiendas AS (
    SELECT
        steam_appid,
        ',' || string_agg(DISTINCT tienda::TEXT, ',') || ',' AS tienda_ids
    FROM public.oferta
    WHERE tienda IS NOT NULL
    GROUP BY steam_appid
)

SELECT
    c.steam_appid,
    c.titulo,
    c.precio_oferta,
    c.ahorro,
    c.oferta_rating,
    c.recent,
    c.reviews,
    c.imagen,
    t.tienda_ids
FROM cheapest c
LEFT JOIN tiendas t USING (steam_appid);

CREATE UNIQUE INDEX IF NOT EXISTS idx_mv_ofertas_unicas_appid
ON public.mv_ofertas_unicas (steam_appid);

COMMIT;
    video varchar(255),
    CONSTRAINT fk_bp_movies
        FOREIGN KEY (bundle_productos_steam_app_id)
        REFERENCES public.bundle_productos(steam_app_id)
        ON DELETE CASCADE
);

-- WISHLIST 

CREATE TABLE IF NOT EXISTS wishlist (
    id_wishlist BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    fecha_agregado TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    user_id UUID NOT NULL UNIQUE,

    CONSTRAINT fk_wishlist_usuario
        FOREIGN KEY (user_id)
        REFERENCES public.usuario(id_usuario)
        ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS wishlist_bundles (
    id_wishlist BIGINT NOT NULL,
    id_bundle BIGINT NOT NULL,

    PRIMARY KEY (id_wishlist, id_bundle),

    CONSTRAINT fk_wishlist_bundles_wishlist
        FOREIGN KEY (id_wishlist)
        REFERENCES public.wishlist(id_wishlist)
        ON DELETE CASCADE,

    CONSTRAINT fk_wishlist_bundles_bundle
        FOREIGN KEY (id_bundle)
        REFERENCES public.bundle(id_bundle)
        ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS wishlist_videojuegos (
    id_wishlist BIGINT NOT NULL,
    id_videojuego BIGINT NOT NULL,

    PRIMARY KEY (id_wishlist, id_videojuego),

    CONSTRAINT fk_wishlist_videojuegos_wishlist
        FOREIGN KEY (id_wishlist)
